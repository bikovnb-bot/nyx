const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("vlessvpn", {
  addProfile: (name, link) => ipcRenderer.invoke("add-profile", { name, link }),
  editProfile: (id, name, link) => ipcRenderer.invoke("edit-profile", { id, name, link }),
  removeProfile: (id) => ipcRenderer.invoke("remove-profile", id),
  connect: (id) => ipcRenderer.invoke("connect-profile", id),
  disconnect: () => ipcRenderer.invoke("disconnect"),
  getState: () => ipcRenderer.invoke("get-state"),
  onState: (cb) => ipcRenderer.on("state", (_evt, state) => cb(state)),
  setAutostart: (enabled) => ipcRenderer.invoke("set-autostart", enabled),
  openLog: () => ipcRenderer.invoke("open-log"),
  quit: () => ipcRenderer.invoke("quit"),
  pingProfile: (id) => ipcRenderer.invoke("ping-profile", id),
  copyLink: (id) => ipcRenderer.invoke("copy-link", id),
  exportProfiles: () => ipcRenderer.invoke("export-profiles"),
  importProfiles: () => ipcRenderer.invoke("import-profiles"),
  getAppInfo: () => ipcRenderer.invoke("get-app-info"),
  onTraffic: (cb) => ipcRenderer.on("traffic", (_evt, data) => cb(data)),
  getUpdateStatus: () => ipcRenderer.invoke("get-update-status"),
  checkForUpdates: () => ipcRenderer.invoke("check-for-updates"),
  installUpdate: () => ipcRenderer.invoke("install-update"),
  onUpdateStatus: (cb) => ipcRenderer.on("update-status", (_evt, status) => cb(status)),
  getSettings: () => ipcRenderer.invoke("get-settings"),
  updateSettings: (partial) => ipcRenderer.invoke("update-settings", partial),
  exportBackup: () => ipcRenderer.invoke("export-backup"),
  importBackup: () => ipcRenderer.invoke("import-backup"),
  getLogTail: () => ipcRenderer.invoke("get-log-tail"),
  getTunnelLatency: () => ipcRenderer.invoke("get-tunnel-latency"),
  quickConnect: () => ipcRenderer.invoke("quick-connect"),
  connectBest: () => ipcRenderer.invoke("connect-best"),
  toggleFavorite: (id) => ipcRenderer.invoke("toggle-favorite", id),
  getProfileQr: (id) => ipcRenderer.invoke("get-profile-qr", id),
  getStats: (days) => ipcRenderer.invoke("get-stats", days),
  addSubscription: (url) => ipcRenderer.invoke("add-subscription", url),
  refreshSubscription: (id) => ipcRenderer.invoke("refresh-subscription", id),
  refreshAllSubscriptions: () => ipcRenderer.invoke("refresh-all-subscriptions"),
  removeSubscription: (id) => ipcRenderer.invoke("remove-subscription", id),
  dismissHint: (name) => ipcRenderer.invoke("dismiss-hint", name),
  minimize: () => ipcRenderer.invoke("window-minimize"),
  maximize: () => ipcRenderer.invoke("window-maximize"),
  close: () => ipcRenderer.invoke("window-close"),
  isMaximized: () => ipcRenderer.invoke("window-is-maximized"),
});
